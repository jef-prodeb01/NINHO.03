-- ==============================================================================
-- SCRIPT DE CARGA INICIAL: REGISTRO PADRÃO DESCONHECIDO (LINHA -1)
-- ==============================================================================
-- Objetivo: Garantir que fatos com chaves nulas ou registros ainda não cadastrados
--           nas fontes dimensionais não quebrem a carga (Early Arriving Facts).
-- Padrão:   DIMENSION_KEY = -1, ID = -1, Vigência desde 1900, Vigente (EXPIRACAO NULL).
-- ==============================================================================

-- 1. Dimensão Exemplo 1
MERGE INTO "<SCHEMA_ALVO>"."DIM_<DOMINIO>_<ENTIDADE_1>" T
USING (
  SELECT -1 AS DIMENSION_KEY, -1 AS ID_<ENTIDADE_1>, 'N/I' AS SIGLA_<ENTIDADE_1>, 
         'NÃO INFORMADO / DESCONHECIDO' AS DS_<ENTIDADE_1>, 'S' AS SIN_ATIVO_<ENTIDADE_1>,
         TO_DATE('1900-01-01', 'YYYY-MM-DD') AS DTC_EFETIVACAO, NULL AS DTC_EXPIRACAO, 'N' AS DES_ATUALIZAR
  FROM DUAL
) S
ON (T.DIMENSION_KEY = S.DIMENSION_KEY)
WHEN NOT MATCHED THEN
  INSERT (DIMENSION_KEY, ID_<ENTIDADE_1>, SIGLA_<ENTIDADE_1>, DS_<ENTIDADE_1>, SIN_ATIVO_<ENTIDADE_1>, DTC_EFETIVACAO, DTC_EXPIRACAO, DES_ATUALIZAR)
  VALUES (S.DIMENSION_KEY, S.ID_<ENTIDADE_1>, S.SIGLA_<ENTIDADE_1>, S.DS_<ENTIDADE_1>, S.SIN_ATIVO_<ENTIDADE_1>, S.DTC_EFETIVACAO, S.DTC_EXPIRACAO, S.DES_ATUALIZAR);

-- 2. Dimensão Exemplo 2
MERGE INTO "<SCHEMA_ALVO>"."DIM_<DOMINIO>_<ENTIDADE_2>" T
USING (
  SELECT -1 AS DIMENSION_KEY, -1 AS ID_<ENTIDADE_2>, 'N/I' AS SIGLA_<ENTIDADE_2>, 
         'NÃO INFORMADO / DESCONHECIDO' AS DS_<ENTIDADE_2>, 'S' AS SIN_ATIVO_<ENTIDADE_2>,
         TO_DATE('1900-01-01', 'YYYY-MM-DD') AS DTC_EFETIVACAO, NULL AS DTC_EXPIRACAO, 'N' AS DES_ATUALIZAR
  FROM DUAL
) S
ON (T.DIMENSION_KEY = S.DIMENSION_KEY)
WHEN NOT MATCHED THEN
  INSERT (DIMENSION_KEY, ID_<ENTIDADE_2>, SIGLA_<ENTIDADE_2>, DS_<ENTIDADE_2>, SIN_ATIVO_<ENTIDADE_2>, DTC_EFETIVACAO, DTC_EXPIRACAO, DES_ATUALIZAR)
  VALUES (S.DIMENSION_KEY, S.ID_<ENTIDADE_2>, S.SIGLA_<ENTIDADE_2>, S.DS_<ENTIDADE_2>, S.SIN_ATIVO_<ENTIDADE_2>, S.DTC_EFETIVACAO, S.DTC_EXPIRACAO, S.DES_ATUALIZAR);

COMMIT;
