-- ==============================================================================
-- Padrão Corporativo: SDM_OLAP.TB_CONTROLE_CARGA
-- Schema Alvo:        <SCHEMA_ALVO>
-- Tablespace:         <TABLESPACE_DADOS>
-- Papel:              Registra início, fim, status (SUCESSO/FALHA) e volumetria de cada carga.
-- ==============================================================================

CREATE TABLE "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA" 
   (	"ID_CARGA" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE, 
	"NOME_PROJETO" VARCHAR2(255) NOT NULL ENABLE, 
	"NOME_TABELA_ALVO" VARCHAR2(100),
	"TIPO_CARGA" VARCHAR2(50), -- TRUNCATE_LOAD / MERGE_INCREMENTAL / SCD2
	"DATA_INICIO" DATE DEFAULT SYSDATE NOT NULL ENABLE,
	"DATA_FIM" DATE,
	"STATUS_EXECUCAO" VARCHAR2(20) DEFAULT 'EM_PROCESSAMENTO' NOT NULL ENABLE, -- SUCESSO / FALHA / EM_PROCESSAMENTO
	"QTD_LINHAS_PROCESSADAS" NUMBER(38,0) DEFAULT 0,
	"DES_MENSAGEM_ERRO" VARCHAR2(4000),
	 CONSTRAINT "TB_CONTROLE_CARGA_PK" PRIMARY KEY ("ID_CARGA")
  USING INDEX PCTFREE 10 INITRANS 2 MAXTRANS 255 COMPUTE STATISTICS 
  TABLESPACE "<TABLESPACE_DADOS>" ENABLE
   ) SEGMENT CREATION IMMEDIATE 
  PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255 
  NOCOMPRESS LOGGING
  TABLESPACE "<TABLESPACE_DADOS>";

COMMENT ON TABLE "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA" IS 'Tabela corporativa de auditoria e controle de execucao das cargas do DW.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."ID_CARGA" IS 'Identificador unico sequencial e incremental da execucao de carga.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."NOME_PROJETO" IS 'Nome do projeto de DW associado a execucao da carga.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."NOME_TABELA_ALVO" IS 'Nome da tabela fato ou dimensao processada.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."TIPO_CARGA" IS 'Estrategia utilizada: TRUNCATE_LOAD, MERGE_INCREMENTAL ou SCD2.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."DATA_INICIO" IS 'Data e hora exata do inicio da execucao da carga.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."DATA_FIM" IS 'Data e hora exata da conclusao da carga.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."STATUS_EXECUCAO" IS 'Status final do processo: SUCESSO, FALHA ou EM_PROCESSAMENTO.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."QTD_LINHAS_PROCESSADAS" IS 'Quantidade de registros gravados ou afetados na carga.';
COMMENT ON COLUMN "<SCHEMA_ALVO>"."TB_CONTROLE_CARGA"."DES_MENSAGEM_ERRO" IS 'Mensagem descritiva de erro técnico em caso de falha.';
