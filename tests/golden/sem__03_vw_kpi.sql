-- -----------------------------------------------------------------------------
-- View Camada 3: DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO
-- Grão: Uma linha representa o consolidado de indicadores de LICITACAO_CONTRATO agrupado por DIM_ORGAO_PUBLICO e por DIM_TEMPO.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FORCE VIEW DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO AS
SELECT
    e.DIM_ORGAO_PUBLICO AS DIM_ORGAO_PUBLICO,
    e.DIM_TEMPO AS DIM_TEMPO,
    COUNT(1) AS QTD_TOTAL_REGISTROS,
    SUM(NVL(e.QTD_ITENS_CONTRATO, 0)) AS SUM_QTD_ITENS_CONTRATO,
    ROUND(AVG(NVL(e.QTD_ITENS_CONTRATO, 0)), 2) AS AVG_QTD_ITENS_CONTRATO,
    SUM(NVL(e.VAL_ESTIMADO, 0)) AS SUM_VAL_ESTIMADO,
    ROUND(AVG(NVL(e.VAL_ESTIMADO, 0)), 2) AS AVG_VAL_ESTIMADO,
    SUM(NVL(e.VAL_CONTRATO, 0)) AS SUM_VAL_CONTRATO,
    ROUND(AVG(NVL(e.VAL_CONTRATO, 0)), 2) AS AVG_VAL_CONTRATO,
    SUM(NVL(e.VAL_PAGO_ACUMULADO, 0)) AS SUM_VAL_PAGO_ACUMULADO,
    ROUND(AVG(NVL(e.VAL_PAGO_ACUMULADO, 0)), 2) AS AVG_VAL_PAGO_ACUMULADO,
    ROUND((COUNT(1) * 100.0) / NULLIF(SUM(COUNT(1)) OVER (PARTITION BY e.DIM_TEMPO), 0), 2) AS PCT_PARTICIPACAO_TOTAL
FROM DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO e
GROUP BY e.DIM_ORGAO_PUBLICO, e.DIM_TEMPO;

COMMENT ON TABLE DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO IS 'View semântica pré-agregada de KPIs executivos de FATO_LICITACAO_CONTRATO. Uma linha representa o consolidado de indicadores de LICITACAO_CONTRATO agrupado por DIM_ORGAO_PUBLICO e por DIM_TEMPO.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.DIM_ORGAO_PUBLICO IS 'Eixo dimensional de agrupamento (DIM_ORGAO_PUBLICO).';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.DIM_TEMPO IS 'Eixo temporal do KPI: Chave da dimensão de tempo (DIM_TEMPO).';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.QTD_TOTAL_REGISTROS IS 'Volume total de eventos contabilizados em FATO_LICITACAO_CONTRATO.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.SUM_QTD_ITENS_CONTRATO IS 'Somatório da métrica QTD_ITENS_CONTRATO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.AVG_QTD_ITENS_CONTRATO IS 'Média aritmética da métrica QTD_ITENS_CONTRATO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.SUM_VAL_ESTIMADO IS 'Somatório da métrica VAL_ESTIMADO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.AVG_VAL_ESTIMADO IS 'Média aritmética da métrica VAL_ESTIMADO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.SUM_VAL_CONTRATO IS 'Somatório da métrica VAL_CONTRATO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.AVG_VAL_CONTRATO IS 'Média aritmética da métrica VAL_CONTRATO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.SUM_VAL_PAGO_ACUMULADO IS 'Somatório da métrica VAL_PAGO_ACUMULADO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.AVG_VAL_PAGO_ACUMULADO IS 'Média aritmética da métrica VAL_PAGO_ACUMULADO no agrupamento.';
COMMENT ON COLUMN DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO.PCT_PARTICIPACAO_TOTAL IS 'Percentual de participação do grupo sobre o volume total do período (divisão segura com NULLIF).';
