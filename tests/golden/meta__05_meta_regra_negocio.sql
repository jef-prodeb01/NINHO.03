MERGE INTO DW_GLD.META_REGRA_NEGOCIO dst
USING (SELECT 'GLD' AS PROJETO, 'RN_GLD_001: Toda consulta em dimensão histórica para estado atual deve filtrar DTC_EXPIRACAO IS NULL.' AS REGRA, 'ALTA' AS SEVERIDADE, 'ATIVA' AS STATUS_REGRA, 'FILTRO_SCD2' AS CONTEXTO, 'Expressão SQL padrão: DTC_EXPIRACAO IS NULL' AS OBSERVACAO FROM DUAL) src
ON (dst.PROJETO = src.PROJETO AND dst.REGRA = src.REGRA)
WHEN MATCHED THEN UPDATE SET dst.SEVERIDADE = src.SEVERIDADE, dst.STATUS_REGRA = src.STATUS_REGRA, dst.OBSERVACAO = src.OBSERVACAO
WHEN NOT MATCHED THEN INSERT (PROJETO, REGRA, SEVERIDADE, STATUS_REGRA, CONTEXTO, OBSERVACAO)
VALUES (src.PROJETO, src.REGRA, src.SEVERIDADE, src.STATUS_REGRA, src.CONTEXTO, src.OBSERVACAO);

MERGE INTO DW_GLD.META_REGRA_NEGOCIO dst
USING (SELECT 'GLD' AS PROJETO, 'RN_GLD_002: Chaves estrangeiras não informadas na origem são mapeadas para SK = -1 (Não Informado) evitando perda de fatos em INNER JOIN.' AS REGRA, 'ALTA' AS SEVERIDADE, 'ATIVA' AS STATUS_REGRA, 'INTEGRIDADE_DIMENSIONAL' AS CONTEXTO, 'Expressão SQL padrão: NVL(SK_DIM, -1)' AS OBSERVACAO FROM DUAL) src
ON (dst.PROJETO = src.PROJETO AND dst.REGRA = src.REGRA)
WHEN MATCHED THEN UPDATE SET dst.SEVERIDADE = src.SEVERIDADE, dst.STATUS_REGRA = src.STATUS_REGRA, dst.OBSERVACAO = src.OBSERVACAO
WHEN NOT MATCHED THEN INSERT (PROJETO, REGRA, SEVERIDADE, STATUS_REGRA, CONTEXTO, OBSERVACAO)
VALUES (src.PROJETO, src.REGRA, src.SEVERIDADE, src.STATUS_REGRA, src.CONTEXTO, src.OBSERVACAO);

COMMIT;
