MERGE INTO DW_GLD.META_VALOR_DOMINIO dst
USING (SELECT 'GLD' AS PROJETO, 'GLOBAL' AS NOME_OBJETO, 'SIN_ATIVO' AS NOME_COLUNA, 'S' AS VALOR, 'Sim / Verdadeiro / Registro Vigente' AS DESCRICAO, 'S' AS IND_ATIVO FROM DUAL) src
ON (dst.PROJETO = src.PROJETO AND dst.NOME_OBJETO = src.NOME_OBJETO AND dst.NOME_COLUNA = src.NOME_COLUNA AND dst.VALOR = src.VALOR)
WHEN MATCHED THEN UPDATE SET dst.DESCRICAO = src.DESCRICAO, dst.IND_ATIVO = src.IND_ATIVO
WHEN NOT MATCHED THEN INSERT (PROJETO, NOME_OBJETO, NOME_COLUNA, VALOR, DESCRICAO, IND_ATIVO) VALUES (src.PROJETO, src.NOME_OBJETO, src.NOME_COLUNA, src.VALOR, src.DESCRICAO, src.IND_ATIVO);

MERGE INTO DW_GLD.META_VALOR_DOMINIO dst
USING (SELECT 'GLD' AS PROJETO, 'GLOBAL' AS NOME_OBJETO, 'SIN_ATIVO' AS NOME_COLUNA, 'N' AS VALOR, 'Não / Falso / Registro Histórico Expirado' AS DESCRICAO, 'S' AS IND_ATIVO FROM DUAL) src
ON (dst.PROJETO = src.PROJETO AND dst.NOME_OBJETO = src.NOME_OBJETO AND dst.NOME_COLUNA = src.NOME_COLUNA AND dst.VALOR = src.VALOR)
WHEN MATCHED THEN UPDATE SET dst.DESCRICAO = src.DESCRICAO, dst.IND_ATIVO = src.IND_ATIVO
WHEN NOT MATCHED THEN INSERT (PROJETO, NOME_OBJETO, NOME_COLUNA, VALOR, DESCRICAO, IND_ATIVO) VALUES (src.PROJETO, src.NOME_OBJETO, src.NOME_COLUNA, src.VALOR, src.DESCRICAO, src.IND_ATIVO);

MERGE INTO DW_GLD.META_VALOR_DOMINIO dst
USING (SELECT 'GLD' AS PROJETO, 'GLOBAL' AS NOME_OBJETO, 'SK_SENTINELA' AS NOME_COLUNA, '-1' AS VALOR, 'Não Informado / Não Aplicável na Origem' AS DESCRICAO, 'S' AS IND_ATIVO FROM DUAL) src
ON (dst.PROJETO = src.PROJETO AND dst.NOME_OBJETO = src.NOME_OBJETO AND dst.NOME_COLUNA = src.NOME_COLUNA AND dst.VALOR = src.VALOR)
WHEN MATCHED THEN UPDATE SET dst.DESCRICAO = src.DESCRICAO, dst.IND_ATIVO = src.IND_ATIVO
WHEN NOT MATCHED THEN INSERT (PROJETO, NOME_OBJETO, NOME_COLUNA, VALOR, DESCRICAO, IND_ATIVO) VALUES (src.PROJETO, src.NOME_OBJETO, src.NOME_COLUNA, src.VALOR, src.DESCRICAO, src.IND_ATIVO);

COMMIT;
