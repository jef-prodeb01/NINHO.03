-- 1. Criação idempotente de ETA_ETAPAS_CARGA (Padrão Apache Hop / ODI 12c)
DECLARE
    e_table_exists EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_table_exists, -955);
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE DW_GLD.ETA_ETAPAS_CARGA (
            ETA_COD_ETAPA           NUMBER(10)          NOT NULL,
            ETA_DES_ETAPA           VARCHAR2(200 CHAR)  NOT NULL,
            ETA_TABELA_ALVO         VARCHAR2(100 CHAR)  NOT NULL,
            ETA_DATA_ULT_ATUALIZACAO DATE               DEFAULT SYSDATE NOT NULL,
            ETA_STATUS_ULT_EXECUCAO VARCHAR2(30 CHAR)   DEFAULT ''PENDENTE'' NOT NULL,
            CONSTRAINT PK_ETA_ETAPAS_CARGA PRIMARY KEY (ETA_COD_ETAPA) USING INDEX TABLESPACE GLD_INDEX
        ) TABLESPACE GLD_DATA
    ';
EXCEPTION
    WHEN e_table_exists THEN NULL;
END;
/

COMMENT ON TABLE DW_GLD.ETA_ETAPAS_CARGA IS 'Tabela corporativa de controle de etapas de carga ETL (Apache Hop / ODI 12c). Uma linha representa uma etapa monitorada do pipeline.';
COMMENT ON COLUMN DW_GLD.ETA_ETAPAS_CARGA.ETA_COD_ETAPA IS 'Código identificador sequencial da etapa de carga (PK).';
COMMENT ON COLUMN DW_GLD.ETA_ETAPAS_CARGA.ETA_DES_ETAPA IS 'Descrição funcional da etapa de extração/transformação/carga.';
COMMENT ON COLUMN DW_GLD.ETA_ETAPAS_CARGA.ETA_TABELA_ALVO IS 'Nome físico da tabela alvo (STG_*, DIM_* ou FATO_*) atualizada pela etapa.';
COMMENT ON COLUMN DW_GLD.ETA_ETAPAS_CARGA.ETA_DATA_ULT_ATUALIZACAO IS 'Data e hora da última execução bem-sucedida da etapa.';
COMMENT ON COLUMN DW_GLD.ETA_ETAPAS_CARGA.ETA_STATUS_ULT_EXECUCAO IS 'Status operacional da última execução (SUCESSO, ERRO, EM_ANDAMENTO, PENDENTE).';

-- Registro idempotente das etapas do projeto em ETA_ETAPAS_CARGA
MERGE INTO DW_GLD.ETA_ETAPAS_CARGA T
USING (SELECT 1 AS COD, 'Carga Stage STG_ORGAO_PUBLICO' AS DES, 'STG_ORGAO_PUBLICO' AS ALVO FROM DUAL) S
ON (T.ETA_COD_ETAPA = S.COD)
WHEN NOT MATCHED THEN
    INSERT (ETA_COD_ETAPA, ETA_DES_ETAPA, ETA_TABELA_ALVO, ETA_DATA_ULT_ATUALIZACAO, ETA_STATUS_ULT_EXECUCAO)
    VALUES (S.COD, S.DES, S.ALVO, SYSDATE, 'PENDENTE');
MERGE INTO DW_GLD.ETA_ETAPAS_CARGA T
USING (SELECT 2 AS COD, 'Carga Dimensão SCD2 DIM_ORGAO_PUBLICO' AS DES, 'DIM_ORGAO_PUBLICO' AS ALVO FROM DUAL) S
ON (T.ETA_COD_ETAPA = S.COD)
WHEN NOT MATCHED THEN
    INSERT (ETA_COD_ETAPA, ETA_DES_ETAPA, ETA_TABELA_ALVO, ETA_DATA_ULT_ATUALIZACAO, ETA_STATUS_ULT_EXECUCAO)
    VALUES (S.COD, S.DES, S.ALVO, SYSDATE, 'PENDENTE');
MERGE INTO DW_GLD.ETA_ETAPAS_CARGA T
USING (SELECT 3 AS COD, 'Carga Stage STG_FORNECEDOR' AS DES, 'STG_FORNECEDOR' AS ALVO FROM DUAL) S
ON (T.ETA_COD_ETAPA = S.COD)
WHEN NOT MATCHED THEN
    INSERT (ETA_COD_ETAPA, ETA_DES_ETAPA, ETA_TABELA_ALVO, ETA_DATA_ULT_ATUALIZACAO, ETA_STATUS_ULT_EXECUCAO)
    VALUES (S.COD, S.DES, S.ALVO, SYSDATE, 'PENDENTE');
MERGE INTO DW_GLD.ETA_ETAPAS_CARGA T
USING (SELECT 4 AS COD, 'Carga Dimensão SCD2 DIM_FORNECEDOR' AS DES, 'DIM_FORNECEDOR' AS ALVO FROM DUAL) S
ON (T.ETA_COD_ETAPA = S.COD)
WHEN NOT MATCHED THEN
    INSERT (ETA_COD_ETAPA, ETA_DES_ETAPA, ETA_TABELA_ALVO, ETA_DATA_ULT_ATUALIZACAO, ETA_STATUS_ULT_EXECUCAO)
    VALUES (S.COD, S.DES, S.ALVO, SYSDATE, 'PENDENTE');
MERGE INTO DW_GLD.ETA_ETAPAS_CARGA T
USING (SELECT 5 AS COD, 'Carga Stage STG_LICITACAO_CONTRATO' AS DES, 'STG_LICITACAO_CONTRATO' AS ALVO FROM DUAL) S
ON (T.ETA_COD_ETAPA = S.COD)
WHEN NOT MATCHED THEN
    INSERT (ETA_COD_ETAPA, ETA_DES_ETAPA, ETA_TABELA_ALVO, ETA_DATA_ULT_ATUALIZACAO, ETA_STATUS_ULT_EXECUCAO)
    VALUES (S.COD, S.DES, S.ALVO, SYSDATE, 'PENDENTE');
MERGE INTO DW_GLD.ETA_ETAPAS_CARGA T
USING (SELECT 6 AS COD, 'Carga Tabela Fato FATO_LICITACAO_CONTRATO' AS DES, 'FATO_LICITACAO_CONTRATO' AS ALVO FROM DUAL) S
ON (T.ETA_COD_ETAPA = S.COD)
WHEN NOT MATCHED THEN
    INSERT (ETA_COD_ETAPA, ETA_DES_ETAPA, ETA_TABELA_ALVO, ETA_DATA_ULT_ATUALIZACAO, ETA_STATUS_ULT_EXECUCAO)
    VALUES (S.COD, S.DES, S.ALVO, SYSDATE, 'PENDENTE');
COMMIT;

-- 2. Tabela complementar de telemetria detalhada de lotes (TB_CONTROLE_CARGA)
CREATE TABLE DW_GLD.TB_CONTROLE_CARGA (
    COD_CARGA         NUMBER(10)          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SGL_PROJETO       VARCHAR2(50 CHAR)   DEFAULT 'GLD' NOT NULL,
    NOM_OBJETO_ALVO   VARCHAR2(128 CHAR)  NOT NULL,
    TIP_CAMADA        VARCHAR2(20 CHAR)   NOT NULL,
    DTC_INICIO_CARGA  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    DTC_FIM_CARGA     TIMESTAMP           NULL,
    QTD_LIDOS         NUMBER(15)          DEFAULT 0,
    QTD_INSERIDOS     NUMBER(15)          DEFAULT 0,
    QTD_ATUALIZADOS   NUMBER(15)          DEFAULT 0,
    QTD_REJEITADOS    NUMBER(15)          DEFAULT 0,
    IND_STATUS        VARCHAR2(20 CHAR)   DEFAULT 'EM_ANDAMENTO' NOT NULL,
    DES_MENSAGEM_ERRO VARCHAR2(4000 CHAR) NULL,
    CONSTRAINT PK_TB_CONTROLE_CARGA PRIMARY KEY (COD_CARGA) USING INDEX TABLESPACE GLD_INDEX
) TABLESPACE GLD_DATA;

COMMENT ON TABLE DW_GLD.TB_CONTROLE_CARGA IS 'Tabela corporativa de auditoria e telemetria de execução de cargas ETL (STG/DIM/FATO). Uma linha representa uma execução de lote.';
