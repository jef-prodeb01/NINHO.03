-- -----------------------------------------------------------------------------
-- View Camada 2: DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO
-- Grão: Uma linha representa um evento individual registrado em FATO_LICITACAO_CONTRATO enriquecido com suas dimensões.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FORCE VIEW DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO AS
SELECT
    f.DIM_ORGAO_PUBLICO AS DIM_ORGAO_PUBLICO,
    f.DIM_FORNECEDOR AS DIM_FORNECEDOR,
    f.QTD_ITENS_CONTRATO AS QTD_ITENS_CONTRATO,
    f.VAL_ESTIMADO AS VAL_ESTIMADO,
    f.VAL_CONTRATO AS VAL_CONTRATO,
    f.VAL_PAGO_ACUMULADO AS VAL_PAGO_ACUMULADO,
    f.DIM_TEMPO AS DIM_TEMPO,
    d1.ID_ORGAO AS ID_ORGAO_ORGAO_PUBLICO,
    NVL(d1.SIG_ORGAO, 'Não Informado') AS SIG_ORGAO_ORGAO_PUBLICO,
    NVL(d1.NOM_ORGAO, 'Não Informado') AS NOM_ORGAO_ORGAO_PUBLICO,
    d2.ID_FORNECEDOR AS ID_FORNECEDOR,
    d2.NUM_CNPJ AS NUM_CNPJ_FORNECEDOR,
    NVL(d2.NOM_FORNECEDOR, 'Não Informado') AS NOM_FORNECEDOR
FROM DW_GLD.FATO_LICITACAO_CONTRATO f
LEFT JOIN DW_GLD.DIM_ORGAO_PUBLICO d1 ON f.DIM_ORGAO_PUBLICO = d1.DIMENSION_KEY
LEFT JOIN DW_GLD.DIM_FORNECEDOR d2 ON f.DIM_FORNECEDOR = d2.DIMENSION_KEY;

COMMENT ON TABLE DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO IS 'View semântica de eventos detalhados de FATO_LICITACAO_CONTRATO. Uma linha representa um evento individual registrado em FATO_LICITACAO_CONTRATO enriquecido com suas dimensões.';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.DIM_ORGAO_PUBLICO IS 'Chave estrangeira (FK) referenciando DIM_ORGAO_PUBLICO(DIMENSION_KEY).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.DIM_FORNECEDOR IS 'Chave estrangeira (FK) referenciando DIM_FORNECEDOR(DIMENSION_KEY).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.QTD_ITENS_CONTRATO IS 'Quantidade apurada ou contagem de Itens Contrato. Métrica Aditiva (SUM) na tabela Fato.';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.VAL_ESTIMADO IS 'Valor monetário ou quantitativo de Estimado. Métrica Aditiva (SUM) na tabela Fato.';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.VAL_CONTRATO IS 'Valor monetário ou quantitativo de Contrato. Métrica Aditiva (SUM) na tabela Fato.';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.VAL_PAGO_ACUMULADO IS 'Valor monetário ou quantitativo de Pago Acumulado. Métrica Aditiva (SUM) na tabela Fato.';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.DIM_TEMPO IS 'Chave estrangeira (FK) para a dimensão calendário conformada DIM_TEMPO(DIMENSION_KEY).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.ID_ORGAO_ORGAO_PUBLICO IS 'Atributo ID_ORGAO oriundo da dimensão DIM_ORGAO_PUBLICO (DIM_ORGAO_PUBLICO).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.SIG_ORGAO_ORGAO_PUBLICO IS 'Atributo SIG_ORGAO oriundo da dimensão DIM_ORGAO_PUBLICO (DIM_ORGAO_PUBLICO).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.NOM_ORGAO_ORGAO_PUBLICO IS 'Atributo NOM_ORGAO oriundo da dimensão DIM_ORGAO_PUBLICO (DIM_ORGAO_PUBLICO).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.ID_FORNECEDOR IS 'Atributo ID_FORNECEDOR oriundo da dimensão DIM_FORNECEDOR (DIM_FORNECEDOR).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.NUM_CNPJ_FORNECEDOR IS 'Atributo NUM_CNPJ oriundo da dimensão DIM_FORNECEDOR (DIM_FORNECEDOR).';
COMMENT ON COLUMN DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO.NOM_FORNECEDOR IS 'Atributo NOM_FORNECEDOR oriundo da dimensão DIM_FORNECEDOR (DIM_FORNECEDOR).';
