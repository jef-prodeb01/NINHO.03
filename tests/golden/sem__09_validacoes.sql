-- 1. Verificação de Objetos Inválidos no Schema
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS WHERE OWNER = 'DW_GLD' AND OBJECT_NAME LIKE 'VW_GLD_%' AND STATUS <> 'VALID';

-- 2. Contagem de Registros nas Views de Dimensão Vigente (Camada 1)
SELECT 'VW_GLD_DIM_ORGAO_PUBLICO_ATUAL' AS VIEW_SEMANTICA, COUNT(1) AS QTD_VIGENTES FROM DW_GLD.VW_GLD_DIM_ORGAO_PUBLICO_ATUAL;
SELECT 'VW_GLD_DIM_FORNECEDOR_ATUAL' AS VIEW_SEMANTICA, COUNT(1) AS QTD_VIGENTES FROM DW_GLD.VW_GLD_DIM_FORNECEDOR_ATUAL;

-- 3. Contagem de Registros nas Views de Evento (Camada 2) e KPIs (Camada 3)
SELECT 'VW_GLD_EVENTO_LICITACAO_CONTRATO' AS VIEW_EVENTO, COUNT(1) AS QTD_LINHAS FROM DW_GLD.VW_GLD_EVENTO_LICITACAO_CONTRATO;
SELECT 'VW_GLD_KPI_LICITACAO_CONTRATO' AS VIEW_KPI, COUNT(1) AS QTD_GRUPOS, SUM(QTD_TOTAL_REGISTROS) AS SOMA_EVENTOS FROM DW_GLD.VW_GLD_KPI_LICITACAO_CONTRATO;

-- 4. Auditoria de Preenchimento do Catálogo META_* para o Projeto
SELECT 'META_GLOSSARIO' AS TABELA, COUNT(1) AS QTD FROM DW_GLD.META_GLOSSARIO WHERE PROJETO = 'GLD'
UNION ALL
SELECT 'META_METRICA', COUNT(1) FROM DW_GLD.META_METRICA WHERE PROJETO = 'GLD'
UNION ALL
SELECT 'META_OBJETO', COUNT(1) FROM DW_GLD.META_OBJETO WHERE PROJETO = 'GLD'
UNION ALL
SELECT 'META_RELACIONAMENTO', COUNT(1) FROM DW_GLD.META_RELACIONAMENTO WHERE PROJETO = 'GLD'
UNION ALL
SELECT 'META_REGRA_NEGOCIO', COUNT(1) FROM DW_GLD.META_REGRA_NEGOCIO WHERE PROJETO = 'GLD'
UNION ALL
SELECT 'META_CONSULTA_NEGOCIO', COUNT(1) FROM DW_GLD.META_CONSULTA_NEGOCIO WHERE PROJETO = 'GLD'
UNION ALL
SELECT 'META_ORIENTACAO_IA', COUNT(1) FROM DW_GLD.META_ORIENTACAO_IA WHERE PROJETO IN ('GLD', 'GLOBAL')
UNION ALL
SELECT 'META_VALOR_DOMINIO', COUNT(1) FROM DW_GLD.META_VALOR_DOMINIO WHERE PROJETO = 'GLD';
